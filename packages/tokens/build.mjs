// Builds dist/tokens.css and dist/tokens.ts from src/*.json (W3C Design Tokens format).
// Plain Node, no dependencies. Output must match kickoff/reference/tokens.css exactly.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const read = (name) => JSON.parse(readFileSync(join(here, "src", name), "utf8"));

const primitives = read("primitives.json");
const light = read("semantic.light.json");
const dark = read("semantic.dark.json");
const foundation = read("foundation.json");

/** Walk a token group, yielding [path[], token] for every node with a $value, in file order. */
function* leaves(node, path = []) {
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith("$")) continue;
    if (child && typeof child === "object" && "$value" in child) yield [[...path, key], child];
    else if (child && typeof child === "object") yield* leaves(child, [...path, key]);
  }
}

const cssName = (path) => `--av-${path.join("-")}`;
const REF = /^\{([^}]+)\}$/;

/** Resolve a "{color.seal.700}" reference to a primitive token, returning its path. */
function resolveRef(ref) {
  const path = ref.split(".");
  let node = primitives;
  for (const part of path) {
    node = node?.[part];
    if (node === undefined) throw new Error(`Unresolved token reference {${ref}}`);
  }
  if (!("$value" in node)) throw new Error(`Reference {${ref}} is not a token`);
  if (REF.test(String(node.$value))) throw new Error(`Nested reference in {${ref}}`);
  return { path: path.slice(1), value: node.$value };
}

/** Semantic map: name → { ref: primitive css var, value: resolved hex }. */
function semantic(file) {
  const out = {};
  for (const [path, token] of leaves(file.color)) {
    const name = path.join("-");
    const m = REF.exec(String(token.$value));
    if (!m) throw new Error(`Semantic token ${name} must reference a primitive`);
    const { path: primPath, value } = resolveRef(m[1]);
    out[name] = { ref: cssName(primPath), value };
  }
  return out;
}

const lightMap = semantic(light);
const darkMap = semantic(dark);
const semanticNames = Object.keys(lightMap);
for (const name of semanticNames) {
  if (!darkMap[name]) throw new Error(`Semantic token ${name} missing from dark theme`);
}
for (const name of Object.keys(darkMap)) {
  if (!lightMap[name]) throw new Error(`Semantic token ${name} missing from light theme`);
}

// ---- CSS -------------------------------------------------------------------------------------
const root = [];
for (const [path, token] of leaves(primitives.color)) {
  if (path[0] === "viz-dark") continue; // dark viz values are emitted in the dark block
  root.push(`  ${cssName(path)}: ${token.$value};`);
}
for (const name of semanticNames) root.push(`  --av-${name}: var(${lightMap[name].ref});`);

const f = foundation;
for (const [key, token] of Object.entries(f.font.family)) {
  root.push(`  --av-font-${key}: ${token.$value};`);
}
for (const [style, props] of Object.entries(f.text)) {
  const parts = ["size", "line", "weight", "tracking"].map(
    (p) => `--av-text-${style}-${p}: ${props[p].$value};`,
  );
  root.push(`  ${parts.join(" ")}`);
}
for (const [key, token] of Object.entries(f.radius)) root.push(`  --av-radius-${key}: ${token.$value};`);
for (const key of ["overlay", "dialog"]) root.push(`  --av-shadow-${key}: ${f.shadow[key].$value};`);
for (const [key, token] of Object.entries(f.motion)) root.push(`  --av-motion-${key}: ${token.$value};`);
for (const [key, token] of Object.entries(f.size)) root.push(`  --av-size-${key}: ${token.$value};`);
for (const [key, token] of Object.entries(f.z)) root.push(`  --av-z-${key}: ${token.$value};`);

const darkBlock = [];
for (const name of semanticNames) darkBlock.push(`  --av-${name}: var(${darkMap[name].ref});`);
for (const [path, token] of leaves(primitives.color["viz-dark"])) {
  darkBlock.push(`  --av-viz-${path.join("-")}: ${token.$value};`);
}
for (const key of ["overlay", "dialog"]) {
  darkBlock.push(`  --av-shadow-${key}: ${f.shadow[`${key}-dark`].$value};`);
}

const css = [
  "/* GENERATED by packages/tokens/build.mjs from packages/tokens/src/*.json. Do not edit by hand. */",
  "/* Reference output: the build must reproduce this file exactly (test: tokens.snapshot.test). */",
  "",
  ":root {",
  "  color-scheme: light;",
  ...root,
  "}",
  "",
  '[data-theme="dark"] {',
  "  color-scheme: dark;",
  ...darkBlock,
  "}",
  "",
  "@media (prefers-reduced-motion: reduce) {",
  "  :root { --av-motion-fast: 0ms; --av-motion-base: 0ms; --av-motion-slow: 0ms; }",
  "}",
  "",
].join("\n");

// ---- TS --------------------------------------------------------------------------------------
const colorObject = (map) =>
  Object.fromEntries(Object.entries(map).map(([name, { value }]) => [name, value]));

const foundationValues = {};
for (const [path, token] of leaves(foundation)) {
  let node = foundationValues;
  for (const part of path.slice(0, -1)) node = node[part] ??= {};
  node[path.at(-1)] = token.$value;
}

const ts = `// GENERATED by packages/tokens/build.mjs. Do not edit by hand.

export const semanticColors = ${JSON.stringify(semanticNames, null, 2)} as const;

export type SemanticColor = (typeof semanticColors)[number];

/** Foundation values (type, space, radius, shadow, motion, size, z-index, breakpoints). */
export const foundation = ${JSON.stringify(foundationValues, null, 2)} as const;

export const tokens = {
  color: {
    light: ${JSON.stringify(colorObject(lightMap), null, 2).replace(/\n/g, "\n    ")} as Record<SemanticColor, string>,
    dark: ${JSON.stringify(colorObject(darkMap), null, 2).replace(/\n/g, "\n    ")} as Record<SemanticColor, string>,
  },
  foundation,
} as const;

/** CSS custom property for a semantic colour, e.g. cssVar("bg-surface") → "var(--av-bg-surface)". */
export const cssVar = (name: SemanticColor): string => \`var(--av-\${name})\`;
`;

mkdirSync(join(here, "dist"), { recursive: true });
writeFileSync(join(here, "dist", "tokens.css"), css);
writeFileSync(join(here, "dist", "tokens.ts"), ts);
console.log(`tokens: ${semanticNames.length} semantic colours → dist/tokens.css, dist/tokens.ts`);
